CREATE TABLE asset_categories (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    organization_id BIGINT NOT NULL DEFAULT 1,
    category_code VARCHAR(24) NOT NULL,
    category_name VARCHAR(120) NOT NULL,
    description TEXT,
    default_depreciation_method VARCHAR(32) NOT NULL DEFAULT 'STRAIGHT_LINE',
    useful_life_years INT NOT NULL DEFAULT 3,
    residual_value_percentage DECIMAL(7,4) NOT NULL DEFAULT 0,
    depreciation_frequency VARCHAR(24) NOT NULL DEFAULT 'MONTHLY',
    default_asset_condition VARCHAR(24) NOT NULL DEFAULT 'GOOD',
    display_color VARCHAR(16) NOT NULL DEFAULT '#ef1f2c',
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    notes TEXT,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_asset_category_code UNIQUE (organization_id, category_code),
    CONSTRAINT uk_asset_category_name UNIQUE (organization_id, category_name),
    INDEX idx_asset_category_status (organization_id, status, deleted)
);

CREATE TABLE assets (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    organization_id BIGINT NOT NULL DEFAULT 1,
    asset_number VARCHAR(48) NOT NULL,
    asset_name VARCHAR(180) NOT NULL,
    category_id BIGINT NOT NULL,
    sub_category VARCHAR(120),
    asset_type VARCHAR(24) NOT NULL DEFAULT 'TANGIBLE',
    brand VARCHAR(100),
    model VARCHAR(100),
    serial_number VARCHAR(120),
    barcode VARCHAR(120),
    quantity DECIMAL(14,3) NOT NULL DEFAULT 1,
    unit VARCHAR(32),
    asset_condition VARCHAR(24) NOT NULL DEFAULT 'GOOD',
    status VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
    vendor_id BIGINT,
    vendor_name VARCHAR(180),
    purchase_date DATE,
    invoice_number VARCHAR(100),
    po_number VARCHAR(100),
    purchase_value DECIMAL(18,2) NOT NULL DEFAULT 0,
    tax_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
    total_amount DECIMAL(18,2) NOT NULL DEFAULT 0,
    payment_method VARCHAR(64),
    warranty_expiry DATE,
    location_name VARCHAR(120),
    department_name VARCHAR(120),
    floor_room VARCHAR(120),
    cost_center VARCHAR(120),
    assigned_resource_id BIGINT,
    assigned_resource_name VARCHAR(180),
    ownership_type VARCHAR(24) NOT NULL DEFAULT 'OWNED',
    lease_start_date DATE,
    lease_end_date DATE,
    manufacturer VARCHAR(120),
    manufacture_year INT,
    country_of_origin VARCHAR(100),
    hsn_sac_code VARCHAR(32),
    useful_life_months INT,
    notes TEXT,
    depreciation_method VARCHAR(32),
    depreciation_start_date DATE,
    depreciation_frequency VARCHAR(24),
    residual_value DECIMAL(18,2) NOT NULL DEFAULT 0,
    scrap_value DECIMAL(18,2) NOT NULL DEFAULT 0,
    capitalization_date DATE,
    current_value DECIMAL(18,2) NOT NULL DEFAULT 0,
    accumulated_depreciation DECIMAL(18,2) NOT NULL DEFAULT 0,
    net_book_value DECIMAL(18,2) NOT NULL DEFAULT 0,
    image_url VARCHAR(1000),
    is_draft BOOLEAN NOT NULL DEFAULT FALSE,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_by VARCHAR(120) NOT NULL DEFAULT 'Admin',
    updated_by VARCHAR(120) NOT NULL DEFAULT 'Admin',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_asset_number UNIQUE (organization_id, asset_number),
    CONSTRAINT fk_asset_category FOREIGN KEY (category_id) REFERENCES asset_categories(id),
    CONSTRAINT fk_asset_vendor FOREIGN KEY (vendor_id) REFERENCES vendors(id),
    INDEX idx_asset_search (organization_id, status, category_id, deleted),
    INDEX idx_asset_purchase_date (organization_id, purchase_date),
    INDEX idx_asset_assignment (organization_id, assigned_resource_id, status),
    INDEX idx_asset_serial (organization_id, serial_number)
);

CREATE TABLE asset_attachments (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    asset_id BIGINT NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_url VARCHAR(1000) NOT NULL,
    content_type VARCHAR(100),
    file_size BIGINT,
    attachment_type VARCHAR(40) NOT NULL DEFAULT 'ASSET',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT fk_asset_attachment_asset FOREIGN KEY (asset_id) REFERENCES assets(id) ON DELETE CASCADE,
    INDEX idx_asset_attachment (asset_id, attachment_type)
);

