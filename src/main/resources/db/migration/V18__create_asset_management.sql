CREATE TABLE asset_depreciation_schedules (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    organization_id BIGINT NOT NULL DEFAULT 1,
    asset_id BIGINT NOT NULL,
    method VARCHAR(32) NOT NULL,
    financial_year VARCHAR(16) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    frequency VARCHAR(24) NOT NULL,
    number_of_periods INT NOT NULL,
    residual_value_type VARCHAR(24) NOT NULL DEFAULT 'FIXED_AMOUNT',
    residual_value DECIMAL(18,2) NOT NULL DEFAULT 0,
    depreciable_amount DECIMAL(18,2) NOT NULL,
    depreciation_per_period DECIMAL(18,2) NOT NULL,
    depreciation_expense_account VARCHAR(160),
    accumulated_depreciation_account VARCHAR(160),
    pro_rata_convention VARCHAR(32) NOT NULL DEFAULT 'FULL_MONTH',
    depreciate_in_purchase_month BOOLEAN NOT NULL DEFAULT TRUE,
    include_in_run BOOLEAN NOT NULL DEFAULT TRUE,
    description TEXT,
    status VARCHAR(24) NOT NULL DEFAULT 'DRAFT',
    last_run_at DATETIME(6),
    next_run_date DATE,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_by VARCHAR(120) NOT NULL DEFAULT 'Admin',
    updated_by VARCHAR(120) NOT NULL DEFAULT 'Admin',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_depreciation_schedule_asset FOREIGN KEY (asset_id) REFERENCES assets(id),
    INDEX idx_depreciation_schedule (organization_id, status, next_run_date, deleted),
    INDEX idx_depreciation_asset (asset_id, start_date)
);

CREATE TABLE asset_depreciation_entries (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    schedule_id BIGINT NOT NULL,
    asset_id BIGINT NOT NULL,
    financial_year VARCHAR(16) NOT NULL,
    period_number INT NOT NULL,
    period_label VARCHAR(40) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    opening_book_value DECIMAL(18,2) NOT NULL,
    depreciation_amount DECIMAL(18,2) NOT NULL,
    accumulated_depreciation DECIMAL(18,2) NOT NULL,
    closing_book_value DECIMAL(18,2) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    posted_at DATETIME(6),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT fk_depreciation_entry_schedule FOREIGN KEY (schedule_id) REFERENCES asset_depreciation_schedules(id) ON DELETE CASCADE,
    CONSTRAINT fk_depreciation_entry_asset FOREIGN KEY (asset_id) REFERENCES assets(id),
    CONSTRAINT uk_depreciation_period UNIQUE (schedule_id, period_number),
    INDEX idx_depreciation_entry_asset (asset_id, start_date, status)
);

