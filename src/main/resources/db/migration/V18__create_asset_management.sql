CREATE TABLE asset_history (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    organization_id BIGINT NOT NULL DEFAULT 1,
    asset_id BIGINT NOT NULL,
    event_type VARCHAR(48) NOT NULL,
    from_status VARCHAR(32),
    to_status VARCHAR(32),
    reference_type VARCHAR(48),
    reference_id BIGINT,
    description VARCHAR(1000) NOT NULL,
    actor VARCHAR(120) NOT NULL DEFAULT 'Admin',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT fk_asset_history_asset FOREIGN KEY (asset_id) REFERENCES assets(id),
    INDEX idx_asset_history (asset_id, created_at),
    INDEX idx_asset_history_org (organization_id, event_type, created_at)
);

