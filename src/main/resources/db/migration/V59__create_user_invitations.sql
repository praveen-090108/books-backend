CREATE TABLE user_invitations (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    resource_id BIGINT NOT NULL,
    token_hash CHAR(64) NOT NULL,
    status VARCHAR(24) NOT NULL,
    delivery_status VARCHAR(24) NOT NULL,
    expires_at DATETIME(6) NOT NULL,
    sent_at DATETIME(6) NULL,
    accepted_at DATETIME(6) NULL,
    revoked_at DATETIME(6) NULL,
    last_delivery_error VARCHAR(500) NULL,
    created_by BIGINT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    CONSTRAINT uk_user_invitations_token UNIQUE (token_hash),
    CONSTRAINT fk_user_invitations_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_invitations_user FOREIGN KEY (user_id) REFERENCES app_users(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_invitations_resource FOREIGN KEY (resource_id) REFERENCES business_records(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_invitations_creator FOREIGN KEY (created_by) REFERENCES app_users(id) ON DELETE SET NULL,
    INDEX idx_user_invitations_org_user (organization_id,user_id,status),
    INDEX idx_user_invitations_expiry (status,expires_at)
);
